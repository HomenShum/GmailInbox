#!/usr/bin/env node
// Create a clean public distribution tree without copying private local data,
// generated media, or internal dogfood logs.

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.resolve(process.argv[2] ?? path.join(repoRoot, "out-public"));

const includeRoots = new Set([
  ".env.example",
  ".gitignore",
  "README.md",
  "SETUP_GMAIL.md",
  "bun.lock",
  "mcp-server",
  "next-env.d.ts",
  "next.config.ts",
  "package-lock.json",
  "package.json",
  "postcss.config.mjs",
  "public",
  "remotion",
  "scripts",
  "src",
  "tailwind.config.ts",
  "tsconfig.json",
]);

const includeDocs = new Set([
  "docs/RUNTIME.md",
  "docs/linkedin-demo-video.md",
  "docs/publication-checklist.md",
  "docs/publication-decisions.md",
]);

const excludedSegments = new Set([
  ".git",
  ".next",
  ".playwright-mcp",
  ".serena",
  ".turbo",
  ".vercel",
  "dist",
  "node_modules",
  "out",
  "out-public",
  "playwright-report",
  "reports",
  "snapshots",
  "test-results",
]);

const excludedExact = new Set([
  "PLAN.md",
  "PARITY_PLAN.md",
  "V0.2_STATUS.md",
  "public/demo.gif",
  "public/all-time-identity-mindmap.html",
  "public/all-time-identity-mindmap.json",
  "public/job-recruiter-signal-journey.html",
  "public/job-recruiter-signal-journey.json",
  "docs/engineering-decision-log.md",
  "docs/nodebench-gmail-bridge.md",
  "docs/performance-and-product-principles.md",
  "docs/private-context-pipeline-learning-points.md",
]);

const excludedPrefixes = [
  ".claude/",
  ".idea/",
  ".vscode/",
  "docs/sitflow-hifi/",
  "exact_parity_UI_reference/",
  "public/demo/",
  "public/remotion-assets/",
  "public/remotion-generated/",
  "scripts/output/",
  "src/data/",
];

const publicDemoExceptions = new Set(["public/demo/README.md"]);
publicDemoExceptions.add("public/demo/gmail-workspace-public-demo.gif");
publicDemoExceptions.add("public/demo/gmail-workspace-public-demo-poster.png");

await resetOutDir();

const copied = [];

for (const root of includeRoots) {
  await copyPublicPath(root);
}
for (const doc of includeDocs) {
  await copyPublicPath(doc);
}

await fs.writeFile(
  path.join(outDir, "PUBLIC_EXPORT.md"),
  [
    "# Public Export",
    "",
    "This tree was generated by `npm run public:export`.",
    "",
    "It intentionally excludes local Gmail databases, OAuth token material, generated videos/screenshots, private identity outputs, and internal dogfood logs.",
    "",
    "Before pushing this export to a public repository, run:",
    "",
    "```bash",
    "rg -n \"gmail.com|Downloads|client_secret|refresh_token|access_token|BEGIN PRIVATE|local private path\" .",
    "npm run typecheck",
    "npm run build",
    "```",
    "",
  ].join("\n"),
);

console.log(`public export: ${outDir}`);
console.log(`copied files: ${copied.length}`);

async function copyPublicPath(relativePath) {
  const normalized = normalize(relativePath);
  if (!isIncluded(normalized) || isExcluded(normalized)) return;
  const source = path.join(repoRoot, normalized);
  const target = path.join(outDir, normalized);
  const stat = await fs.stat(source).catch(() => null);
  if (!stat) return;

  if (stat.isDirectory()) {
    await walkAndCopy(normalized);
    return;
  }

  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.copyFile(source, target);
  copied.push(normalized);
}

async function walkAndCopy(relativeDir) {
  const absoluteDir = path.join(repoRoot, relativeDir);
  const entries = await fs.readdir(absoluteDir, { withFileTypes: true }).catch(() => []);
  for (const entry of entries) {
    const child = normalize(path.join(relativeDir, entry.name));
    if (isExcluded(child)) continue;
    if (entry.isDirectory()) {
      await walkAndCopy(child);
      continue;
    }
    if (!entry.isFile()) continue;
    if (!isIncluded(child)) continue;
    await copyPublicPath(child);
  }
}

function isIncluded(relativePath) {
  if (includeDocs.has(relativePath)) return true;
  const first = relativePath.split("/")[0];
  return includeRoots.has(relativePath) || includeRoots.has(first);
}

function isExcluded(relativePath) {
  const normalized = normalize(relativePath);
  if (publicDemoExceptions.has(normalized)) return false;
  if (excludedExact.has(normalized)) return true;
  if (normalized.startsWith(".env") && normalized !== ".env.example") return true;
  if (normalized.includes("client_secret_")) return true;
  if (normalized === "NUL") return true;
  if (normalized.endsWith(".log") || normalized.endsWith(".tsbuildinfo")) return true;
  if (normalized.endsWith(".db") || normalized.endsWith(".db-shm") || normalized.endsWith(".db-wal")) return true;
  if (normalized.endsWith(".mp4") || normalized.endsWith(".webm") || normalized.endsWith(".gif")) return true;
  if (normalized.endsWith(".png") && !normalized.startsWith("public/remotion-public-assets/")) return true;
  if (normalized.endsWith(".jpg") || normalized.endsWith(".jpeg") || normalized.endsWith(".webp")) return true;
  if (normalized.endsWith(".m4a")) return true;
  if (excludedSegments.has(normalized.split("/")[0])) return true;
  return excludedPrefixes.some((prefix) => normalized.startsWith(prefix));
}

function normalize(value) {
  return value.replaceAll("\\", "/").replace(/^\/+/, "");
}

async function resetOutDir() {
  const gitDir = path.join(outDir, ".git");
  const hasGit = await fs.stat(gitDir).then((stat) => stat.isDirectory()).catch(() => false);
  if (!hasGit) {
    await fs.rm(outDir, { recursive: true, force: true });
    await fs.mkdir(outDir, { recursive: true });
    return;
  }

  await fs.mkdir(outDir, { recursive: true });
  const entries = await fs.readdir(outDir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name === ".git") continue;
    await fs.rm(path.join(outDir, entry.name), { recursive: true, force: true });
  }
}
